static inline void draw_char(SDL_Renderer *r, char c, int x, int y, SDL_Color color) {
    if (c < 32 || c > 126) return;
    const unsigned char *glyph = font8x8[c - 32];
    SDL_SetRenderDrawColor(r, color.r, color.g, color.b, color.a);
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            if (glyph[row] & (1 << (7 - col))) {
                SDL_RenderDrawPoint(r, x + col, y + row);
            }
        }
    }
}

static inline void draw_text(SDL_Renderer *r, const char *str, int x, int y, SDL_Color color) {
    int cur_x = x;
    while (*str) {
        draw_char(r, *str, cur_x, y, color);
        cur_x += 8;
        str++;
    }
}

